"""Static Computation Graph Comparator and Structural Analyzer.

Compares computation graphs generated by ggmlc against reference architectures
and implementations (such as llama.cpp), analyzing:
- Node counts and operator breakdowns
- Horizontal operator fusions (QKV, Gate+Up)
- Normalization and attention fusions
- Memory arena reuse planning efficiency
- Kernel dispatch and execution topology
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any

from ggmlc.dialect.ggml.lowering import GGMLExecutionGraph
from ggmlc.dialect.ggml.ops import GGMLOpCode, GGMLType
from ggmlc.ir.graph import Graph
from ggmlc.ir.op import OpCode
from ggmlc.ir.tensor import StorageClass


@dataclass
class GraphAnalysis:
    """Detailed structural metrics of a computation graph."""

    name: str
    total_nodes: int
    total_tensors: int
    parameter_count: int
    parameter_size_mb: float
    opcode_counts: dict[str, int] = field(default_factory=dict)
    category_counts: dict[str, int] = field(default_factory=dict)
    fused_qkv_count: int = 0
    fused_gate_up_count: int = 0
    fused_norm_count: int = 0
    total_fused_ops: int = 0
    kernel_launch_reduction_pct: float = 0.0
    planned_arena_size_mb: float = 0.0
    unplanned_buffer_size_mb: float = 0.0
    arena_reuse_efficiency_pct: float = 0.0


@dataclass
class ModelGraphComparison:
    """Side-by-side structural comparison between ggmlc and llama.cpp."""

    architecture: str
    model_name: str
    ggmlc_nodes: int
    llamacpp_estimated_nodes: int
    node_reduction_pct: float
    ggmlc_gemv_launches: int
    llamacpp_gemv_launches: int
    gemv_reduction_pct: float
    ggmlc_fusion_details: str
    llamacpp_construction: str
    memory_strategy_ggmlc: str
    memory_strategy_llamacpp: str
    cuda_graph_support_ggmlc: str
    cuda_graph_support_llamacpp: str
    notes: str = ""


