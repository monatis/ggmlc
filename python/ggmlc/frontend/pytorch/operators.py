def get_opcode_for_aten(target: Any) -> OpCode | None:
    name = str(target)
    if name in ATEN_OP_MAP:
        return ATEN_OP_MAP[name]
    # Fallback to string name matching
    for k, v in ATEN_OP_MAP.items():
        if k in name:
            return v
    return None
